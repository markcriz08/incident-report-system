const fs = require('fs');
const path = require('path');
require('dotenv').config();

const outputPath = path.join(__dirname, '..', 'public', 'js', 'supabase-config.js');
const url = process.env.SUPABASE_URL || 'https://riwfxzjtyytybfanfyoz.supabase.co';
const anonKey = process.env.SUPABASE_ANON_KEY || '';

if (!anonKey) {
  console.warn('SUPABASE_ANON_KEY is not set. The viewer will remain in configuration-needed mode.');
}

const content = `// Generated by Netlify build. Public publishable key only.\nwindow.IR_SUPABASE_CONFIG = ${JSON.stringify({ url, anonKey }, null, 2)};\n`;
fs.writeFileSync(outputPath, content);
console.log('Generated public Supabase viewer configuration.');
